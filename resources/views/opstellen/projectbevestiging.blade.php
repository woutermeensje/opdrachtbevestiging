        <li>De planning met mijlpalen en opleverdata</li>
        <li>Het budget of de vaste prijs, eventueel verdeeld over fases</li>
        <li>Hoe je omgaat met meerwerk en wijzigingen</li>
        <li>Wat je van de opdrachtgever nodig hebt, zoals input of toegang</li>
        <li>De facturatiemomenten en betaaltermijn</li>
    </ul>

