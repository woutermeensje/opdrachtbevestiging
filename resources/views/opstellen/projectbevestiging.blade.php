    <h2>Wat is een projectbevestiging?</h2>
    <p>Een projectbevestiging is een opdrachtbevestiging voor een project met een duidelijk begin en eind. Je legt vast wat je oplevert, wanneer en voor welk budget. Denk aan een websitebouw, een verbouwing, een implementatie of een adviestraject in meerdere fases.</p>

    <h2>Waarom een projectbevestiging?</h2>
    <p>Bij projecten ontstaat discussie vaak over de scope: wat hoort er wel bij en wat is meerwerk? Door de opdracht vooraf goed af te bakenen en afspraken over wijzigingen vast te leggen, houd je grip op planning en budget. Heeft het project meerdere fases, dan kun je per fase vastleggen wat er wordt opgeleverd en wanneer je factureert.</p>

    <h2>Wat zet je in een projectbevestiging?</h2>
    <ul>
        <li>Het doel en de omschrijving van het project</li>
